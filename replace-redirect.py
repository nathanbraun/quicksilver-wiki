def replace_contents_with_redirected(directory, target_files):
    """
    Replaces the contents of the files in the specified directory
    if the file path matches any of the target files.

    directory: The directory to search (top-level only)
    target_files: A list of file paths to match
    """
    # List all files in the top-level directory
    for file in os.listdir(directory):
        file_path = os.path.join(directory, file)
        
        # Check if it's a file and matches any in the target files
        if os.path.isfile(file_path) and file in target_files:
            with open(file_path, 'w') as f:
                f.write('Redirected')

